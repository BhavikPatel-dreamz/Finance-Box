// Downloads the live WPGraphQL schema and writes it as SDL so codegen and
// section fragments are validated against what WordPress actually exposes.
// Usage: npm run schema   (reads WORDPRESS_GRAPHQL_URL from .env / environment)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { buildClientSchema, getIntrospectionQuery, printSchema } from "graphql";

function loadEnvFile() {
  if (!existsSync(".env")) return;
  for (const line of readFileSync(".env", "utf8").split("\n")) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match && !(match[1] in process.env)) process.env[match[1]] = match[2].replace(/^["']|["']$/g, "");
  }
}

loadEnvFile();
const endpoint = process.env.WORDPRESS_GRAPHQL_URL;
if (!endpoint) {
  console.error("WORDPRESS_GRAPHQL_URL is not set.");
  process.exit(1);
}

let body;
for (let attempt = 1; attempt <= 3; attempt += 1) {
  try {
    const response = await fetch(endpoint, {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({ query: getIntrospectionQuery({ descriptions: false }) }),
      signal: AbortSignal.timeout(60_000),
    });
    body = await response.json();
    if (body?.data) break;
  } catch (error) {
    if (attempt === 3) throw error;
  }
  await new Promise((resolve) => setTimeout(resolve, attempt * 1000));
}

if (!body?.data) {
  console.error("Introspection failed:", JSON.stringify(body?.errors ?? body).slice(0, 500));
  process.exit(1);
}

const sdl = printSchema(buildClientSchema(body.data));
const header = `# Generated by scripts/fetch-schema.mjs from ${endpoint}\n# Do not edit by hand. Run \`npm run schema\` to refresh.\n\n`;
writeFileSync("src/lib/wordpress/schema.graphql", header + sdl);
console.log(`Wrote src/lib/wordpress/schema.graphql (${sdl.length} bytes).`);
